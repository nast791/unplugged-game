/**
 * Сторона поля за местом игрока. Место (seat) — это порядок игрока в партии; номерная клетка героя
 * помечена `position` = место + 1, поэтому сторона однозначно читается из клетки.
 *
 * Правило простое и жёсткое: **1 — всегда слева, 2 — справа, 3 — сверху, 4 — снизу**, независимо
 * от числа игроков и формы поля. Так игрок всегда знает, где искать свой старт, а маркер номера
 * смотрит наружу именно с этой стороны. Край считается по полю: старт стоит в крайней колонке
 * (строке) поля или в следующей от неё — то есть максимум второй от края, а не где-то в глубине.
 */
export const SEAT_SIDES = { 1: 'left', 2: 'right', 3: 'top', 4: 'bottom' };

/** Сторона места: `position` из номерной клетки (1–4). Неизвестное место стороны не имеет. */
export const seatSide = position => SEAT_SIDES[Number(position)] ?? null;

export default SEAT_SIDES;
