/**
 * Словарь подсказок партии — **все тексты, которые игрок читает сверху экрана, в одном файле**.
 *
 *
 * **Правила словаря:**
 * 1. **Ключ — `<имя фазы>.<ключ>`**, ровно как в `hints` самой фазы (`HINTS.place.placeFighters` ↔
 *    `phases/place.js: hints.placeFighters`); группа `client` — подсказки клиента, движок их не знает.
 *    Совпадение ключей один к одному стережёт `tests/unit/content/hints.test.js`.
 * 2. **Значение — функция**, даже для неподвижного текста: у неё один аргумент — контекст с уже
 *    посчитанными значениями (`{ name }`, `{ limit, count }`, `{ cells }`). Статическая подсказка
 *    контекст игнорирует, поэтому в фазе стоит прямой ссылкой (`text: HINTS.place.placeFighters`),
 *    а динамическая — обёрткой, которая считает контекст (`text: state => HINTS.attack.waitingDefense({ … })`).
 * 3. **Ветки формулировки — тоже текст, и живут здесь.** «Выберите клетку» против «выберите бойца»,
 *    хвост необязательного окна, «защиту съели» — это варианты одной подсказки, а не разные подсказки:
 *    фаза передаёт признак (`{ cells: true }`, `{ required: true }`), словарь выбирает слова. Так в фазу
 *    не возвращается ни одна строка.
 * 4. **«Когда показывать» остаётся в фазе** — поле `active` рядом с тем состоянием, которое оно читает.
 *    Условия разные (`combat.stage`, `isDefender`, открытое окно эффекта), и переносить их сюда значило бы
 *    тащить в константы внутренности фаз. Словарь знает слова, фаза — момент.
 * 5. **Текст окна умения — из контента** (`choose.skillWindow`): его пишет пак героя
 *    (`server/content/heroes/*`), словарь только приводит его к строке — переводить его сюда нельзя.
 */

/** Хвост необязательного окна эффекта: у обязательного выбора его нет. Один на все окна боя. */
const optionalTail = ' — или закончите эффект без выбора';
const optional = pick => `${pick}${optionalTail}`;

export const HINTS = {
  /** `pickNumHero` — выбор героя на номерную клетку (у кого героев больше одного). */
  pickNumHero: {
    /** Герой ещё не выбран — открыта модалка с портретами. */
    chooseHero: () => 'Выберите одного из героев, который будет размещен на номерной клетке поля',
    /** Герой выбран и стоит на номерной клетке как предпросмотр — ждём подтверждения. */
    confirmHero: () => 'Подтвердите выбор героя',
  },

  /** `place` — расстановка бойцов в области героя. */
  place: {
    /** Все бойцы стоят на клетках, но игрок ещё не подтвердил — «ОК» единственный шаг. */
    confirmFighters: () => 'Все бойцы расставлены — подтвердите расстановку кнопкой «ОК»',
    /** Пока игрок не подтвердил свою расстановку. */
    placeFighters: () =>
      'Разместите на поле всех своих бойцов. Их можно ставить на подсвеченные клетки области героя',
    /** Клетку бойца занял другой игрок: боец вернулся на полку, его ставят заново. */
    cellTaken: ({ name }) =>
      `Клетку занял другой игрок: поставьте ${name} заново на свободную подсвеченную клетку`,
    /** Своя расстановка подтверждена, но кто-то ещё расставляет. */
    waitingForAllPlayers: () => 'Ожидание расстановки бойцов всех игроков',
  },

  /** `handLimit` — начало хода с переполненной рукой. */
  handLimit: {
    /** `limit` — лимит руки, `count` — сколько осталось сбросить. */
    discardCards: ({ limit, count }) => `Рука больше ${limit} карт: сбросьте ещё ${count}`,
  },

  /** `choose` — фаза объявления действия в свой ход. */
  choose: {
    /** Открыто окно умения героя: текст приходит из пака. */
    skillWindow: ({ text, toggle, picked, required }) => {
      const base = text ?? '';
      if (!toggle) return base;
      if (Number(picked) > 0) {
        return `${base} Цель отмечена: «Завершить умение» применит выбор, повторный клик снимает отметку.`;
      }
      return required
        ? `${base} Отметьте цель кликом, затем нажмите «Завершить умение».`
        : `${base} Отметьте цель кликом, затем нажмите «Завершить умение» — без отметки умение пропускается.`;
    },
    /** Открыт выбор цели: клетки и бойцы звучат по-разному (`cells` — что именно подсвечено). */
    pickTarget: ({ cells, count, picked }) => {
      if (Number(count) > 1) {
        const text = cells
          ? 'Отметьте нужные клетки среди подсвеченных'
          : 'Отметьте нужные цели среди подсвеченных бойцов';
        return `${text} (выбрано ${Number(picked) || 0} из ${Number(count)})`;
      }
      return cells
        ? 'Выберите клетку среди подсвеченных'
        : 'Выберите цель среди подсвеченных бойцов';
    },
    /** Обычный ход: ничего не открыто, есть действия. */
    chooseAction: () =>
      'Ваш ход: возьмите карту из колоды, чтобы переместиться, или разыграйте карту атаки',
  },

  /** `movement` — окно перемещения. */
  movement: {
    /** `fromEffect` — двигает свойство карты (закрывается «Закончить эффект»), иначе обычный маневр. */
    moveFighters: ({ fromEffect }) =>
      fromEffect
        ? 'Передвиньте бойцов по подсвеченным клеткам или закончите эффект'
        : 'Двигайте своих бойцов по подсвеченным клеткам или закончите действие',
  },

  /** `attack` — объявление атаки. */
  attack: {
    /** Боец ещё не выбран. */
    pickAttacker: () => 'Выберите бойца, который атакует этой картой',
    /** Боец выбран, ждём цель. */
    pickTarget: () => 'Выберите цель среди подсвеченных бойцов противника',
    /** Карта объявлена, отвечает защитник: `name` — имя защищающегося. */
    waitingDefense: ({ name }) => `Ожидание защиты игрока ${name}`,
  },

  /** `defense` — защита и паузы свойств карт боя. */
  defense: {
    /** Открыто окно вариантов свойства: `required` — отказаться нельзя; `count` больше 1 — отмечают несколько. */
    effectOption: ({ required, count, picked }) => {
      if (Number(count) > 1) {
        const text = `Отметьте нужные варианты эффекта карты (выбрано ${Number(picked) || 0} из ${Number(count)})`;
        return required ? text : optional(text);
      }
      return required
        ? 'Выберите один из вариантов эффекта карты'
        : optional('Выберите вариант свойства');
    },
    /** Окно цели эффекта: `cells` — выбор клетки, иначе бойца; `required` — отказаться нельзя. */
    effectTarget: ({ cells, required, count, picked }) => {
      if (Number(count) > 1) {
        const text = cells
          ? 'Отметьте нужные клетки среди подсвеченных'
          : 'Отметьте нужные цели среди подсвеченных бойцов';
        const full = `${text} (выбрано ${Number(picked) || 0} из ${Number(count)})`;
        return required ? full : optional(full);
      }
      if (cells)
        return required
          ? 'Выберите клетку среди подсвеченных'
          : optional('Выберите подсвеченную клетку');
      return required
        ? 'Выберите цель среди подсвеченных бойцов'
        : optional('Выберите подсвеченного бойца');
    },
    /** Пауза эффекта: `movement` — он двигает бойцов, иначе выбирает карту из руки. */
    combatChoice: ({ movement }) =>
      movement
        ? 'Передвиньте бойцов по подсвеченным клеткам'
        : optional('Выберите карту для эффекта'),
    /** Защитнику нечем отвечать. */
    noDefenseCards: () => 'Карт защиты нет: закончите действие — защита 0 и весь урон по бойцу',
    /** Обычный ответ на атаку; `afterCancel` — защиту отменили, нужна вторая карта. */
    defend: ({ afterCancel }) =>
      afterCancel
        ? 'Защиту съели: выложите другую карту защиты или гибрид'
        : 'Защититесь картой defense|hybrid или закончите действие без карты',
  },

  /** `waiting` — чужой ход: игрок ничего не делает, только ждёт. */
  waiting: {
    /**
     * Идёт чужая битва: полное окно битвы видят только её участники, остальным достаётся краткая
     * сводка строкой. Карту боя проекция прячет до вскрытия, поэтому в сводке её нет — только стороны
     * (`attacker`/`defender` — имена бойцов с игроками), `numbers` (когда числа уже вскрыты) и `stage`.
     */
    battle: context => {
      const { attacker, defender, numbers } = context ?? {};
      if (!attacker) return 'Идёт чужая битва';
      if (defender == null) return `Идёт битва: ${attacker} выбирает противника`;
      return numbers == null
        ? `Идёт битва: ${attacker} против ${defender}`
        : `Идёт битва: ${attacker} против ${defender} — ${numbers}`;
    },
    /** `name` — чьи бойцы сейчас двигаются. */
    waitingMovement: ({ name }) => `Ждём перемещения бойцов: ${name}`,
    /** `name` — кто выбирает карту для эффекта. */
    waitingChoice: ({ name }) => `Оппонент выбирает карту для эффекта: ${name}`,
    /** `name` — чей ход. */
    waitingTurn: ({ name }) => `Ход игрока ${name}`,
  },

  /** `finished` — партия кончилась: `name` пустое, если победитель почему-то не записан. */
  finished: {
    finished: ({ name }) =>
      name == null ? 'Партия завершена' : `Партия завершена: победа — ${name}`,
  },

  /**
   * Подсказки клиента — их движок не отдаёт: окно показывает их, пока подсказки фазы нет или она устарела
   * (`app/composables/game/useGameHint.js`). Живут здесь, чтобы «где искать подсказку» был один ответ.
   */
  client: {
    /** Ход считает компьютер (`vs_ai`). */
    aiThinking: () => 'Компьютер думает…',
    /** Действие отправлено и ждёт ответа сервера. */
    sending: () => 'Ход отправляется…',
    /** Лимит времени на действие вышел: `limit` — подпись лимита («30 с», «2 мин»). */
    timerExpired: ({ limit }) => `Время действия вышло (${limit}) — игрок выбывает из партии.`,
    /** То же для лимита на расстановку (плашка в расстановке ведёт свой счёт). */
    placementExpired: ({ limit }) =>
      `Время расстановки вышло (${limit}) — кто не успел, выбывает из партии.`,
  },
};

export default HINTS;
